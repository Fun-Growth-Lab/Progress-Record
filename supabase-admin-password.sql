-- 研究進捗アプリ：管理者パスワードの変更
-- Supabase の SQL Editor に貼り付けて Run するだけ（何度でも実行できます）。
--
-- ★ 下の '新しい管理者パスワード' を、あなただけが知るパスワードに書き換えてから実行してください。
--   ・シングルクォート ' の中の文字だけを書き換える（クォートは消さない）
--   ・半角英数字12文字以上を推奨。メールアドレス・名前・誕生日などは使わない
--   ・チーム共通パスワードとは別のものにする
--   ・実行後、このファイルに本物のパスワードを書いたまま保存・共有・アップロードしないこと

update lab_config
   set admin_hash = encode(sha256(convert_to('新しい管理者パスワード', 'UTF8')), 'hex')
 where id = 1;

-- 実行後、古い管理者パスワードは使えなくなります。
-- 管理者モードに入ったままの端末も、次に管理者の操作をしたときにパスワードを聞かれます。
